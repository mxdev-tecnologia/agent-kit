import type { Cli } from "../catalog/collisions.js";
import type { FrontmatterData } from "../schemas/frontmatter.js";
import { InstallError, relPathProblem } from "./apply.js";
import { cmp } from "./lock.js";
import { assertNoMarkers, MAX_BLOCK_BYTES } from "./managed-block.js";

export type ItemType = "skill" | "agent" | "rule" | "workflow";

export interface Asset {
  /** Path inside the skill, for example `references/guide.md`. */
  rel: string;
  data: Buffer;
  exec: boolean;
}

export interface Item {
  type: ItemType;
  name: string;
  data: FrontmatterData;
  /** Whole source text (LF). */
  raw: string;
  /** Text after the frontmatter (LF). */
  body: string;
  assets: Asset[];
  origin: "kit" | "local";
  /** Path of the source shown in messages. */
  source: string;
}

export interface Desired {
  path: string;
  data: Buffer;
  exec?: boolean;
  /** True for AGENTS.md and CLAUDE.md: `data` is the block content, not the whole file. */
  block?: boolean;
}

export interface SharedFile {
  rel: string;
  data: Buffer;
}

const SHARED_DIR: Record<ItemType, string> = {
  skill: ".agents/skills",
  agent: ".agents/agents",
  rule: ".agents/rules",
  workflow: ".agents/workflows",
};

const str = (v: unknown): string => (typeof v === "string" ? v : "");
const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();
const buf = (s: string) => Buffer.from(s, "utf8");

/** Path of the main file of an item in the shared brain. */
export function sharedPath(item: Pick<Item, "type" | "name">): string {
  return item.type === "skill"
    ? `${SHARED_DIR.skill}/${item.name}/SKILL.md`
    : `${SHARED_DIR[item.type]}/${item.name}.md`;
}

const CAPABILITY_TOOLS: [string, string[]][] = [
  ["read", ["Read", "Grep", "Glob"]],
  ["search", ["Grep", "Glob"]],
  ["edit", ["Edit", "Write"]],
  ["shell", ["Bash"]],
  ["web", ["WebFetch", "WebSearch"]],
];

/** Claude Code tools of an agent (RF-12): deduplicated, fixed order, never empty, `mcp` adds none. */
export function claudeTools(capabilities: unknown): string[] {
  const caps = Array.isArray(capabilities) ? capabilities.map(String) : [];
  const tools: string[] = [];
  for (const [cap, mapped] of CAPABILITY_TOOLS) {
    if (!caps.includes(cap)) continue;
    for (const t of mapped) if (!tools.includes(t)) tools.push(t);
  }
  return tools.length > 0 ? tools : ["Read", "Grep", "Glob"];
}

function frontmatter(fields: [string, string][], body: string): Buffer {
  const lines = fields.map(([k, v]) => `${k}: ${k === "name" ? v : JSON.stringify(v)}`);
  return buf(`---\n${lines.join("\n")}\n---\n${body}`);
}

function agentsBlock(items: Item[]): string {
  const out: string[] = [
    "## agent-kit",
    "",
    "This block is managed by agent-kit and is rewritten by `agent-kit update` and `agent-kit sync`. Add project items under `.agents/local/`.",
  ];
  const list = (title: string, entries: Item[]) => {
    if (entries.length === 0) return;
    out.push("", `### ${title}`, "");
    for (const i of entries) {
      out.push(`- \`${i.name}\`: ${oneLine(str(i.data.description))} (\`${sharedPath(i)}\`)`);
    }
  };
  const by = (t: ItemType) => items.filter((i) => i.type === t);
  list("Skills", by("skill"));
  list("Workflows", by("workflow"));
  list("Agents", by("agent"));
  const rules = by("rule");
  const inline = (r: Item) =>
    r.data.always === true || (r.data.always === undefined && !r.data["applies-to"]);
  const inlined = rules.filter(inline);
  const others = rules.filter((r) => !inline(r));
  if (rules.length > 0) out.push("", "### Rules");
  for (const r of inlined) out.push("", `#### ${r.name}`, "", r.body.trim());
  if (others.length > 0) {
    out.push("", "Rules to read when they apply:", "");
    for (const r of others) {
      const globs = Array.isArray(r.data["applies-to"])
        ? ` applies to ${r.data["applies-to"].map((g) => `\`${String(g)}\``).join(", ")};`
        : "";
      out.push(
        `- \`${r.name}\`:${globs} ${oneLine(str(r.data.description))} (\`${sharedPath(r)}\`)`,
      );
    }
  }
  return out.join("\n");
}

/** Generates every desired file for the selected CLIs (RF-07 to RF-14). */
export function buildDesired(
  allItems: Item[],
  clis: readonly Cli[],
  shared: SharedFile[],
  providers: Buffer | undefined,
): Desired[] {
  const items = [...allItems].sort((a, b) => cmp(a.type, b.type) || cmp(a.name, b.name));
  const files = new Map<string, Desired>();
  const add = (d: Desired) => {
    if (files.has(d.path)) throw new InstallError(`${d.path}: generated by more than one item`);
    files.set(d.path, d);
  };
  const assetErrors: string[] = [];
  const assets = (base: string, item: Item) => {
    for (const a of item.assets) {
      const problem = relPathProblem(a.rel);
      if (problem) {
        const dir = item.source.slice(0, item.source.lastIndexOf("/"));
        assetErrors.push(`${dir}/${a.rel}: refused, ${problem}`);
        continue;
      }
      add({ path: `${base}/${a.rel}`, data: a.data, exec: a.exec });
    }
  };

  for (const item of items) {
    add({ path: sharedPath(item), data: buf(item.raw) });
    if (item.type === "skill") assets(`${SHARED_DIR.skill}/${item.name}`, item);
  }
  if (assetErrors.length > 0) throw new InstallError(assetErrors.join("\n"));
  if (providers) add({ path: ".agents/providers.json", data: providers });
  for (const s of shared) add({ path: `.agents/schemas/${s.rel}`, data: s.data });

  // The AGENTS.md block: markers may not appear in anything that enters it.
  for (const item of items) {
    assertNoMarkers(str(item.data.description), item.source);
    if (item.type === "rule") assertNoMarkers(item.body, item.source);
    if (item.type === "rule" && Array.isArray(item.data["applies-to"])) {
      assertNoMarkers(item.data["applies-to"].join(" "), item.source);
    }
  }
  const block = agentsBlock(items);
  const size = Buffer.byteLength(block, "utf8");
  if (size > MAX_BLOCK_BYTES) {
    throw new InstallError(
      `AGENTS.md: the managed block is ${size} bytes, above the ${MAX_BLOCK_BYTES} byte limit`,
    );
  }
  add({ path: "AGENTS.md", data: buf(block), block: true });

  if (clis.includes("claude")) {
    add({ path: "CLAUDE.md", data: buf("@AGENTS.md"), block: true });
    for (const item of items) {
      const description = str(item.data.description);
      if (item.type === "skill") {
        const base = `.claude/skills/${item.name}`;
        add({
          path: `${base}/SKILL.md`,
          data: frontmatter(
            [
              ["name", item.name],
              ["description", description],
            ],
            item.body,
          ),
        });
        assets(base, item);
      } else if (item.type === "agent") {
        const tools = claudeTools(item.data.capabilities).join(", ");
        add({
          path: `.claude/agents/${item.name}.md`,
          data: buf(
            `---\nname: ${item.name}\ndescription: ${JSON.stringify(description)}\ntools: ${tools}\n---\n${item.body}`,
          ),
        });
      } else if (item.type === "workflow") {
        const fields: [string, string][] = [["description", description]];
        const hint = str(item.data["argument-hint"]);
        if (hint !== "") fields.push(["argument-hint", hint]);
        add({ path: `.claude/commands/${item.name}.md`, data: frontmatter(fields, item.body) });
      }
    }
  }
  if (clis.includes("codex")) {
    for (const item of items) {
      if (item.type !== "workflow") continue;
      add({
        path: `${SHARED_DIR.skill}/${item.name}/SKILL.md`,
        data: frontmatter(
          [
            ["name", item.name],
            ["description", str(item.data.description)],
          ],
          item.body,
        ),
      });
    }
  }
  return [...files.values()].sort((a, b) => cmp(a.path, b.path));
}
